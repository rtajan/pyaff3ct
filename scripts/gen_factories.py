#!/usr/bin/env python3
"""Generate the bindings of the AFF3CT factories and the Python module-level functions (Plan.md, phase 2).

Usage:
    python3 scripts/gen_factories.py

Inputs: ``docs/design/aff3ct_api.json`` (API fingerprint: parameters, sub-factories and builders of each factory,
in declaration order), ``aff3ct/_generated/instantiations.py`` (dtype combinations compiled by AFF3CT) and
``docs/design/status.json`` (which module / tool classes are wrapped).

Outputs:

* ``internal/include/internal/Generated/factories.hpp`` + ``internal/src/Generated/factories.cpp`` and one
  ``internal/src/Generated/Factory/<Name>.cpp`` per factory: the class, its parameters (``def_param``), its
  sub-factories (read-only references) and its builders, one method per dtype combination (``build_int32_float32``)
  or ``_<builder>_raw`` for a non-template builder. The modules are returned as ``spu::module::Module*`` so that
  pybind11 types them after the most derived wrapped AFF3CT class (Module downcast registry).
* ``aff3ct/_generated/functions.py``: the module-level functions, the factory being hidden behind them:
  ``aff3ct.dec.polar(K, N_cw, frozen_bits, crc=None, encoder=None, *, type=None, L=None, ..., B=None, Q=None)``.
  Positional: the sizes of the factory (``K``, ``N_cw``, ``N`` declared by its root factory) then the builder
  arguments; keyword-only: every other parameter (``None`` = AFF3CT default) and the template dtypes. One function
  per builder: ``polar`` (``build``), ``polar_siso`` (``build_siso``), ``polar_gen`` (``build_gen``). A function is
  generated only when the class it returns (or one of its bases) is wrapped, according to ``status.json``.
"""

from __future__ import annotations

import json
import pprint
import keyword
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DESIGN = ROOT / "docs" / "design"
INC_GEN = ROOT / "internal" / "include" / "internal" / "Generated"
SRC_GEN = ROOT / "internal" / "src" / "Generated"
PY_GEN = ROOT / "aff3ct" / "_generated"

# Python sub-module of each factory domain (same prefixes as the AFF3CT command line)
DOMAIN_MODULE = {
    "CRC": "crc", "Channel": "chn", "Coset": "cst", "Decoder": "dec", "Encoder": "enc", "Extractor": "ext",
    "Interleaver": "itl", "Modem": "mdm", "Monitor": "mnt", "Puncturer": "pct", "Quantizer": "qnt", "Source": "src",
    "Sink": "snk",
}
SIZES = ("K", "N_cw", "N")  # positional sizes, when declared by the root factory of the family
# classes registered by pystreampu that a builder may return
SPU_REGISTERED = {"Source", "Sink", "Module", "Stateful"}
# builders that cannot be bound (argument types without conversion), with the reason
SKIP_BUILDERS = {
    ("Terminal", "build"): "std::vector<std::unique_ptr<spu::tools::Reporter>> argument (use streampu.Terminal_std)",
}
# factories bound without constructor (bases of a family): the public constructor is ambiguous with a protected one
NO_INIT = {
    "Codec": "Codec(p) and protected Codec(n = Codec_name, p = Codec_prefix) are ambiguous for one string",
}
SCALARS = {
    "int": "int", "unsigned": "int", "unsigned int": "int", "size_t": "int", "std::size_t": "int",
    "uint32_t": "int", "int32_t": "int", "float": "float", "double": "float", "bool": "bool", "std::string": "str",
}
HEADER = "// Generated by scripts/gen_factories.py from docs/design/aff3ct_api.json: do not edit.\n"


def write(path: Path, text: str) -> None:
    """Write only if the content changes (an unchanged file keeps its date: no needless recompilation)."""
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


# --------------------------------------------------------------------------------------------- parsing helpers
def split_top(s: str) -> list[str]:
    out, depth, cur = [], 0, ""
    for ch in s:
        depth += ch in "<({["
        depth -= ch in ">)}]"
        if ch == "," and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    out.append(cur)
    return [x.strip() for x in out if x.strip()]


def split_default(decl: str) -> tuple[str, str | None]:
    # "int L = 8"; a brace initializer is dropped by the fingerprint: "std::vector<int>poly ="
    parts = re.split(r"\s=(?:\s|$)", decl.strip(), maxsplit=1)
    default = parts[1].strip() if len(parts) > 1 else None
    return parts[0].strip(), (default or None)


def split_type_name(decl: str) -> tuple[str, str]:
    m = re.match(r"^(.*?[\w>*&\s])\s*(\w+)$", decl)
    if not m:
        raise ValueError(f"cannot split the declaration {decl!r}")
    return m.group(1).strip(), m.group(2)


def qualify(t: str) -> str:
    """Fully qualify the AFF3CT types written inside `namespace aff3ct { namespace factory {`."""
    t = re.sub(r"(?<![:\w])module::", "aff3ct::module::", t)
    t = re.sub(r"(?<![:\w])tools::", "aff3ct::tools::", t)
    t = re.sub(r"(?<![:\w])factory::", "aff3ct::factory::", t)
    return t


_PY_VECTORS = {"bool": "numpy.ndarray[bool]", "int": "list[int]", "unsigned": "list[int]", "uint32_t": "list[int]",
               "float": "list[float]", "R": "list[float]", "std::vector<int>": "list[list[int]]",
               "std::vector<uint32_t>": "list[list[int]]"}
_PY_MODULES = [("Encoder", "enc"), ("Decoder", "dec"), ("CRC", "crc"), ("Interleaver", "itl"), ("Puncturer", "pct"),
               ("Modem", "mdm"), ("Channel", "chn")]


def py_type(t: str) -> str:
    """Python name of a C++ argument type, for the docstrings ("const aff3ct::module::CRC<B>*" -> "aff3ct.crc.CRC")."""
    t = re.sub(r"\bconst\b|[&*]", "", qualify(t)).strip()
    if t == "R":
        return "float"
    m = re.fullmatch(r"std::vector<\s*(.*?)\s*>", t)
    if m:
        return _PY_VECTORS.get(m.group(1), "list")
    if t.startswith("std::map<"):
        return "dict"
    m = re.fullmatch(r"aff3ct::(module|tools)::(\w+)(<.*>)?", t)
    if m:
        if m.group(1) == "tools":
            return f"aff3ct.tools.{m.group(2)}"
        sub = next((s for prefix, s in _PY_MODULES if m.group(2).startswith(prefix)), None)
        return f"aff3ct.{sub}.{m.group(2)}" if sub else m.group(2)
    return t.replace("::", ".")


LITERAL_DEFAULT = re.compile(r'^(nullptr|true|false|-?[0-9.]+[fuUlL]*|"[^"]*")$')


def parse_builder(sig: str) -> dict | None:
    """'template<typename B = int>module::Encoder<B>* build(const std::vector<bool>& fb)const' -> parts."""
    m = re.match(r"^(?:template<(?P<tpl>.*?)>)?(?:static\s+)?(?P<ret>.*?)\b(?P<name>build\w*)\s*"
                 r"\((?P<args>.*)\)\s*(?:const)?$", sig)
    if not m:
        return None
    tpl = [re.sub(r"^(typename|class)\s+", "", split_default(p)[0]) for p in split_top(m.group("tpl") or "")]
    args = []
    for a in split_top(m.group("args")):
        decl, default = split_default(a)
        typ, name = split_type_name(decl)
        if default is not None and not LITERAL_DEFAULT.match(default):
            # default without Python equivalent (e.g. std::ostream& stream = std::cout): not exposed, so this argument
            # and the following ones keep their C++ default
            break
        args.append({"type": typ, "name": name, "default": default})
    return {"tpl": tpl, "ret": m.group("ret").strip(), "name": m.group("name"), "args": args}


def member_info(decl: str, factories: set[str]) -> dict | None:
    """Kind of binding of a public data member: 'param', 'sub' (sub-factory) or None (not bound)."""
    left, _ = split_default(decl)
    if left.startswith(("static ", "const ")) or "(" in left:
        return None
    try:
        typ, name = split_type_name(left)
    except ValueError:
        return None
    m = re.match(r"^tools::auto_cloned_unique_ptr<\s*(?:factory::)?(\w+)\s*>$", typ)
    if m:
        return {"kind": "sub", "name": name, "factory": m.group(1)} if m.group(1) in factories else None
    py = python_type(typ)
    return {"kind": "param", "name": name, "type": typ, "py": py} if py else None


def python_type(typ: str) -> str | None:
    if typ in SCALARS:
        return SCALARS[typ]
    m = re.match(r"^std::vector<(.*)>$", typ)
    if m:
        inner = m.group(1).strip()
        if inner == "bool":
            return "numpy.ndarray"
        sub = python_type(inner)
        return f"list[{sub}]" if sub else None
    return None


# --------------------------------------------------------------------------------------------- model
def load() -> tuple[dict, dict, dict]:
    api = json.loads((DESIGN / "aff3ct_api.json").read_text())["classes"]
    ns: dict = {}
    exec((PY_GEN / "instantiations.py").read_text(), ns)
    status = json.loads((DESIGN / "status.json").read_text()) if (DESIGN / "status.json").exists() else {}
    return api, ns["INSTANTIATIONS"], status


def factory_classes(api: dict) -> dict[str, dict]:
    """Factories deriving from aff3ct::factory::Factory (Factory itself excluded: bound by hand).

    Class templates (Decoder_turbo<D1 = Decoder_RSC, D2 = D1>) are bound for their default arguments only.
    """
    fac = {k.split("::")[1]: v for k, v in api.items() if k.startswith("Factory::")}

    def derives(name: str, seen=()) -> bool:
        if name == "Factory":
            return True
        return any(derives(re.sub(r"<.*", "", b).split("::")[-1], seen + (name,))
                   for b in fac.get(name, {}).get("bases", []) if b not in seen)

    def defaults_only(v: dict) -> bool:
        return all(split_default(p)[1] is not None for p in v["tpl"])

    return {n: v for n, v in fac.items() if n != "Factory" and defaults_only(v) and derives(n)}


def tpl_defaults(v: dict) -> dict[str, str]:
    """{"D1": "Decoder_RSC", "D2": "Decoder_RSC"} for template<class D1 = Decoder_RSC, class D2 = D1>."""
    res: dict[str, str] = {}
    for p in v["tpl"]:
        decl, default = split_default(p)
        name = decl.split()[-1]
        res[name] = res.get(default, default)
    return res


def cpp_name(name: str, v: dict) -> str:
    return f"aff3ct::factory::{name}" + ("<>" if v["tpl"] else "")


def base_of(v: dict) -> str:
    bases = [re.sub(r"<.*", "", b).split("::")[-1] for b in v["bases"]]
    return bases[0] if bases else "Factory"


def chain(name: str, facs: dict) -> list[str]:
    """[name, base, base of base...] up to (excluded) Factory."""
    out = []
    while name in facs:
        out.append(name)
        name = base_of(facs[name])
    return out


def sub_factories(v: dict) -> list[str]:
    """Factories of the sub-factory members (auto_cloned_unique_ptr<Encoder>...), template defaults resolved."""
    tdef = tpl_defaults(v)
    out = []
    for m in v["members"]:
        m = re.search(r"auto_cloned_unique_ptr<\s*(?:factory::)?(\w+)\s*>", m)
        if m:
            out.append(tdef.get(m.group(1), m.group(1)))
    return out


def ordered(facs: dict) -> list[str]:
    """Registration order: a factory after its base and after the factories of its sub-factories, so that pybind11
    knows their Python types when it writes the signatures (otherwise the raw C++ names: aff3ct::factory::Encoder)."""
    done, visiting, out = set(), set(), []

    def visit(n: str) -> None:
        if n in done or n not in facs or n in visiting:
            return
        visiting.add(n)
        visit(base_of(facs[n]))
        for sub in sub_factories(facs[n]):
            visit(sub)
        visiting.discard(n)
        done.add(n)
        out.append(n)

    for n in sorted(facs):
        visit(n)
    return out


def wrapped_class(api: dict, status: dict, ret: str) -> str | None:
    """Wrapped class of the object returned by a builder: the class itself or its most derived wrapped base
    ("Module::Decoder_SIHO", "Tools::Interleaver_core", "spu::Source"), None if none is wrapped."""
    m = re.match(r"^(?:const\s+)?(?:(spu|aff3ct)::)?(?:(module|tools)::)?(\w+)", ret.replace("aff3ct::", ""))
    if not m:
        return None
    if ret.startswith("spu::"):
        return f"spu::{m.group(3)}" if m.group(3) in SPU_REGISTERED else None
    if m.group(2) != "module":
        # a tool is converted only if its static type is registered (no downcast registry for the tools)
        return f"Tools::{m.group(3)}" if status.get(f"Tools::{m.group(3)}") == "done" else None
    # a module: typed after its most derived wrapped base (Module downcast registry); the interfaces do not count
    todo, seen = [f"Module::{m.group(3)}"], set()
    while todo:
        key = todo.pop(0)  # breadth first: the most derived wrapped base
        if key in seen:
            continue
        seen.add(key)
        if status.get(key) == "done":
            return key
        for b in api.get(key, {}).get("bases", []):
            todo.append("Module::" + re.sub(r"<.*", "", b).split("::")[-1])
    return None


def wrapped(api: dict, status: dict, ret: str) -> bool:
    """True if the class returned by a builder, or one of its bases, is wrapped (status 'done')."""
    return wrapped_class(api, status, ret) is not None


SPU_CLASSES = {"Source": "streampu._ext.src.Source", "Sink": "streampu._ext.snk.Sink"}  # + _<dtype>


def return_annotation(api: dict, status: dict, python_paths: dict, ret: str, combos: list | None) -> str:
    """Annotation of a module-level function: the Python class (or class template) of the object it returns, for the
    autocompletion of the IDEs (``aff3ct.dec.Decoder_SIHO``); ``Any`` when it has no public Python path."""
    key = wrapped_class(api, status, ret)
    if key is None:
        return "Any"
    if key.startswith("spu::"):  # pystreampu classes, one per dtype (no class template object)
        cls = SPU_CLASSES.get(key[5:])
        return " | ".join(f"{cls}_{c[0]}" for c in combos) if cls and combos else "Any"
    return python_paths.get(key, "Any")


BUILTIN_TYPES = {"bool", "int", "unsigned", "float", "double", "size_t", "uint8_t", "uint16_t", "uint32_t",
                 "uint64_t", "int8_t", "int16_t", "int32_t", "int64_t", "B", "Q", "R", "S", "T", "D", "Q1", "Q2",
                 "B1", "B2", "R1", "R2"}


def arg_bindable(status: dict, facs: dict, t: str) -> bool:
    """True if Python can give an argument of this C++ type: builtin, std::, or a class registered with exactly this
    type (pybind11 does not convert a base into a derived class: a Decoder_SISO is not a Decoder_RSC_DB_BCJR)."""
    t = re.sub(r"\bconst\b|[&*]", "", qualify(t)).strip()
    if t in BUILTIN_TYPES or t.startswith("std::"):
        return True
    m = re.fullmatch(r"(aff3ct|spu)::(module|tools|factory)::(\w+)(<.*>)?", t)
    if not m:
        return False
    if m.group(1) == "spu":
        return m.group(3) in SPU_REGISTERED
    if m.group(2) == "factory":
        return m.group(3) in facs or m.group(3) == "Interleaver_core"
    return status.get(f"{'Module' if m.group(2) == 'module' else 'Tools'}::{m.group(3)}") == "done"


UNBOUND_BUILDERS: list[str] = []  # builder overloads without binding (class returned or of a required argument)


def bindable_builder(api: dict, status: dict, facs: dict, b: dict) -> dict | None:
    """The builder limited to the arguments Python can give: its optional arguments up to the first one of a type
    without Python class (tools::Distributions, module::Encoder_BCH...); None if a required argument has such a type
    or if the returned class has no Python class either."""
    if not wrapped(api, status, qualify(b["ret"])):
        return None
    for i, a in enumerate(b["args"]):
        if not arg_bindable(status, facs, a["type"]):
            return None if a["default"] is None else {**b, "args": b["args"][:i]}
    return b


# --------------------------------------------------------------------------------------------- C++ output
def cpp_builder(name: str, b: dict, combos: dict | None) -> str:
    """Bindings of a builder: the full signature and every truncation of its optional trailing arguments.

    pybind11 cannot load ``None`` into a pointer to an unregistered type (``tools::Constellation<R>*``) even when the
    C++ default is ``nullptr``: an overload without the trailing optional arguments lets the C++ defaults apply (the
    Python layer drops the ``None`` arguments).
    """
    first_opt = next((i for i, a in enumerate(b["args"]) if a["default"] is not None), len(b["args"]))
    code = "".join(cpp_builder_overload(name, {**b, "args": b["args"][:n]}, combos)
                   for n in range(first_opt, len(b["args"]) + 1))
    if combos is None:  # non-template builder: recorded once, called by the Python layer as _<builder>_raw
        code += f'    raw_builders.append("{b["name"]}");\n'
    return code


def cpp_builder_overload(name: str, b: dict, combos: dict | None) -> str:
    args = [{**a, "qtype": qualify(a["type"])} for a in b["args"]]
    ret = qualify(b["ret"])
    is_module = "aff3ct::module::" in ret
    ret_cpp = "spu::module::Module*" if is_module else ret
    params = ", ".join(f"{a['qtype']} {a['name']}" for a in args)
    names = ", ".join(a["name"] for a in args)
    extras = []
    for a in args:
        # literal defaults (nullptr, false, 0...) are kept: they let a later argument be given without the previous
        # ones (encoder= without crc=); the shorter overloads cover the pointers to unregistered types, which pybind11
        # cannot load from None
        d = a["default"]
        extras.append(f'py::arg("{a["name"]}")' + (f" = {qualify(d)}" if d is not None else ""))
    for i, a in enumerate(args):
        t = a["qtype"].replace("const ", "").strip()
        if ("*" in t or "&" in t) and not t.startswith("std::"):
            extras.append(f"py::keep_alive<0, {i + 2}>()")  # the module keeps the objects it was built with
    extra = "".join(f",\n          {e}" for e in extras)
    if combos is None:  # non-template builder
        return (f'    cls.def("_{b["name"]}_raw",\n'
                f'            [](const F& f{", " if params else ""}{params}) -> {ret_cpp} '
                f'{{ return f.{b["name"]}({names}); }},\n'
                f'            py::return_value_policy::take_ownership{extra.replace(chr(10) + "          ", chr(10) + "            ")});\n'
                )
    tparams = combos["params"]
    usings = " ".join(f"using {p} = typename decltype(c)::template at<{i}>;" for i, p in enumerate(tparams))
    targs = ", ".join(tparams)
    return (f'    def_builders<gen::Factory_{name}__{b["name"]}>(\n'
            f'      cls,\n      "{b["name"]}",\n'
            f'      [](auto c)\n      {{\n          {usings}\n'
            f'          return [](const F& f{", " if params else ""}{params}) -> {ret_cpp}\n'
            f'          {{ return f.template {b["name"]}<{targs}>({names}); }};\n'
            f'      }}{extra});\n')


def cpp_factory(name: str, v: dict, facs: dict, inst: dict, api: dict, status: dict) -> tuple[str, list[dict]]:
    base = base_of(v)
    lines = [HEADER, f'#include "{v["file"]}"\n', '#include "internal/Generated/factories.hpp"',
             '#include "internal/Wrapper/Factory/Factory.hpp"\n',
             f"void\npyaf::generated::wrap_factory_{name}(py::handle scope)\n{{",
             "    using namespace pyaf::wrapper;",
             f"    using F = {cpp_name(name, v)};",
             f'    py::class_<F, aff3ct::factory::{base}> cls(scope, "{name}", '
             f'"AFF3CT factory ``aff3ct::factory::{name}`` (parameters by keyword, ``from_cli``, builders by dtype).");']
    ctor = v["ctors"][0] if v["ctors"] else []
    if name in NO_INIT or not v["ctors"]:
        # no public constructor (family base, e.g. Decoder) or ambiguous one: not constructible from Python
        reason = NO_INIT.get(name, "no public constructor")
        lines.append(f"    // not constructible from Python: {reason}")
    elif ctor:
        typ, default = split_default(ctor[0])
        d = f" = aff3ct::factory::{default}" if default and re.match(r"^\w+_prefix$", default) else (
            f" = {qualify(default)}" if default else "")
        lines.append(f'    cls.def(py::init<const std::string&>(), "prefix"_a{d});')
    else:
        lines.append("    cls.def(py::init<>());")
    bound = []
    tdef = tpl_defaults(v)
    for m in v["members"]:
        # sub-factories typed by a template parameter (auto_cloned_unique_ptr<D1>): their default factory
        m = re.sub(r"auto_cloned_unique_ptr<(\w+)>", lambda x: f"auto_cloned_unique_ptr<{tdef.get(x.group(1), x.group(1))}>", m)
        info = member_info(m, set(facs) | {"Interleaver_core"})
        if info is None:
            continue
        if info["kind"] == "param":
            lines.append(f'    def_param(cls, "{info["name"]}", &F::{info["name"]}, "{info["py"]}: AFF3CT parameter '
                         f'``{info["name"]}`` (``{info["type"]}``).");')
        else:
            lines.append(f'    cls.def_property_readonly(\n      "{info["name"]}",\n'
                         f'      [](const F& f) {{ return f.{info["name"]}.get(); }},\n'
                         f'      py::return_value_policy::reference_internal,\n'
                         f'      "aff3ct.factory.{info["factory"]}: sub-factory ``{info["name"]}`` (None if not used).");')
        bound.append(info)
    if "void enable_puncturer()" in v["methods"]:
        lines.append('    cls.def("enable_puncturer", &F::enable_puncturer, "Add the puncturer sub-factory ``pct`` (codecs).");')
    builders = []
    raw = False
    for sig in v["methods"]:
        b = parse_builder(sig)
        if b is None or (name, b["name"]) in SKIP_BUILDERS:
            continue
        bound_b = bindable_builder(api, status, facs, b)
        if bound_b is None:
            UNBOUND_BUILDERS.append(f"{name}.{b['name']} -> {b['ret']}")
            continue
        b = bound_b
        combos = inst.get(f"Factory::{name}", {}).get("builders", {}).get(b["name"])
        if b["tpl"] and combos is None:
            continue  # template without explicit instantiation in libaff3ct
        if b["tpl"] and combos["params"] != b["tpl"]:
            continue
        if not b["tpl"]:
            if not raw:
                lines.append("    py::list raw_builders(py::getattr(cls, \"_raw_builders\", py::tuple()));")
                raw = True
        lines.append(cpp_builder(name, b, combos if b["tpl"] else None))
        builders.append({**b, "template": bool(b["tpl"])})
    if raw:
        lines.append('    cls.attr("_raw_builders") = py::tuple(raw_builders);')
    lines.append("}\n")
    return "\n".join(lines), bound, builders


# --------------------------------------------------------------------------------------------- Python output
def py_name(name: str, domain: str, builder: str) -> str:
    short = re.sub(rf"^{re.escape(domain)}_?", "", name).lower() if domain else name.lower()
    short = short or domain.lower()
    return short + ("" if builder == "build" else builder[len("build"):])


def py_ident(n: str) -> str:
    return n + "_" if keyword.iskeyword(n) else n


def main() -> None:
    api, inst, status = load()
    # public Python path of the wrapped classes ("Module::Decoder_SIHO" -> "aff3ct.dec.Decoder_SIHO")
    python_paths = {}
    for c in json.loads((DESIGN / "inventory.json").read_text()):
        if c["kind"] == "Module" and c.get("domain") in DOMAIN_MODULE:
            python_paths[f"Module::{c['name']}"] = f"aff3ct.{DOMAIN_MODULE[c['domain']]}.{c['name']}"
        elif c["kind"] == "Tools":
            python_paths[f"Tools::{c['name']}"] = f"aff3ct.tools.{c['name']}"
    facs = factory_classes(api)
    order = ordered(facs)
    INC_GEN.mkdir(parents=True, exist_ok=True)
    (SRC_GEN / "Factory").mkdir(parents=True, exist_ok=True)

    params_of: dict[str, list[dict]] = {}
    builders_of: dict[str, list[dict]] = {}
    for name in order:
        code, bound, builders = cpp_factory(name, facs[name], facs, inst, api, status)
        write(SRC_GEN / "Factory" / f"{name}.cpp", code)
        params_of[name] = [b for b in bound if b["kind"] == "param"]
        builders_of[name] = builders

    for old in (SRC_GEN / "Factory").glob("*.cpp"):  # factories removed from AFF3CT
        if old.stem not in facs:
            old.unlink()

    decls = "\n".join(f"void\nwrap_factory_{n}(py::handle scope);" for n in order)
    write(INC_GEN / "factories.hpp",
        f"{HEADER}#ifndef PYAF_GENERATED_FACTORIES_HPP_\n#define PYAF_GENERATED_FACTORIES_HPP_\n\n"
        f'#include "internal/internal.hpp"\n\nnamespace pyaf\n{{\nnamespace generated\n{{\n{decls}\n\n'
        f"//! Registers every generated factory in `scope` (bases first).\nvoid\nwrap_factories(py::handle scope);\n"
        f"}} // namespace generated\n}} // namespace pyaf\n\n#endif // PYAF_GENERATED_FACTORIES_HPP_\n")
    calls = "\n".join(f"    wrap_factory_{n}(scope);" for n in order)
    write(SRC_GEN / "factories.cpp",
        f'{HEADER}#include "internal/Generated/factories.hpp"\n\nvoid\npyaf::generated::wrap_factories(py::handle scope)'
        f"\n{{\n{calls}\n}}\n")

    # ------------------------------------------------------------- Python functions
    funcs: dict[str, list[str]] = {}
    code = [
        '# -*- coding: utf-8 -*-\n"""Module-level functions of aff3ct (factories hidden behind them).\n\n'
        'Generated by scripts/gen_factories.py from docs/design/aff3ct_api.json: do not edit.\n"""\n',
        "# flake8: noqa\nfrom __future__ import annotations\n",
        "from typing import Any\n",
        "from aff3ct._factory import make as _make\n",
    ]
    # builders whose every overload is unbound, and builders of a class not wrapped
    bound_names = {f"{n}.{b['name']}" for n in order for b in builders_of[n]}
    skipped = [s for s in dict.fromkeys(UNBOUND_BUILDERS) if s.split(" -> ")[0] not in bound_names]
    codecs: dict[str, dict] = {}
    for name in order:
        v = facs[name]
        parts = Path(v["file"]).parts  # Factory/Module/<Domain>/... or Factory/Tools/...
        if parts[1:3] == ("Tools", "Codec"):
            # codecs: their parameters are those of their sub-factories (enc_type, dec_L...), whose dynamic types are
            # only known at run time: aff3ct/codec.py builds their functions at import (see CODECS)
            for b in builders_of[name]:
                if b["name"] == "build" and len(parts) > 4:  # Factory/Tools/Codec/<Family>/Codec_x.hpp
                    codecs[name] = {"function": py_name(name, "Codec", "build"),
                                    "args": [{"name": a["name"], "type": qualify(a["type"]), "py_type": py_type(a["type"]),
                                              "default": a["default"]} for a in b["args"]]}
            continue
        domain = parts[2] if parts[1] == "Module" else ""
        module = DOMAIN_MODULE.get(domain, "tools") if domain else "tools"
        # positional sizes: those of the highest factory of the family that declares some (factory::Decoder: K, N_cw;
        # factory::Monitor_BFER: K), not the sizes added by a sub-family (Decoder_LDPC::N stays a keyword)
        sizes = []
        for n in reversed(chain(name, facs)):
            sizes = [p["name"] for p in params_of[n] if p["name"] in SIZES]
            if sizes:
                break
        all_params = [p for n in reversed(chain(name, facs)) for p in params_of[n]]
        kw_params = [p for p in all_params if p["name"] not in sizes]
        # overloads of a builder (Channel.build() / build(dist)): one function, union of the arguments; an argument
        # is required only if every overload requires it (pybind11 picks the overload from the given names)
        merged: dict[str, dict] = {}
        for b in builders_of[name]:
            if b["name"] not in merged:
                merged[b["name"]] = {**b, "args": [dict(a) for a in b["args"]], "n": 1}
                continue
            m = merged[b["name"]]
            m["n"] += 1
            names = {a["name"] for a in b["args"]}
            for a in m["args"]:
                if a["name"] not in names and a["default"] is None:
                    a["default"] = "(overload)"
            for a in b["args"]:
                if a["name"] not in {x["name"] for x in m["args"]}:
                    m["args"].append({**a, "default": a["default"] or "(overload)"})
        for b in merged.values():
            if not wrapped(api, status, qualify(b["ret"])):
                skipped.append(f"{name}.{b['name']} -> {b['ret']}")
                continue
            fname = py_name(name, domain, b["name"])
            arg_names = [a["name"] for a in b["args"]]
            clash = set(arg_names) & {p["name"] for p in all_params}
            assert not clash, (name, b["name"], clash)
            dtypes = inst.get(f"Factory::{name}", {}).get("builders", {}).get(b["name"], {}).get("params", []) \
                if b["template"] else []
            sig = [f"{s}: int" for s in sizes]
            sig += [f"{py_ident(a['name'])}: Any" + (" = None" if a["default"] is not None else "") for a in b["args"]]
            # a required builder argument after an optional one would be a syntax error: make it optional
            seen_opt = False
            for i in range(len(sizes), len(sig)):
                if sig[i].endswith("= None"):
                    seen_opt = True
                elif seen_opt:
                    sig[i] += " = None"
            kw = [f"{py_ident(p['name'])}: {p['py'] if p['py'] != 'numpy.ndarray' else 'Any'} | None = None"
                  for p in kw_params]
            kw += [f"{d}: Any = None" for d in dtypes]
            signature = ", ".join(sig + (["*"] + kw if kw else []))
            ret_doc = qualify(b["ret"]).replace("aff3ct::", "")
            doc = [f"Build {ret_doc.rstrip('*')} with the AFF3CT factory ``{name}`` (builder ``{b['name']}``).", ""]
            doc += ["Equivalent to ``aff3ct.factory." + f"{name}(**parameters).{b['name']}(...)``; the parameters left"
                    " to ``None`` keep their AFF3CT default (see ``aff3ct.factory." + f"{name}().parameters``).", ""]
            doc += ["Args:"]
            doc += [f"    {s} (int): size (factory parameter)." for s in sizes]
            doc += [f"    {py_ident(a['name'])} ({py_type(a['type'])}): builder argument ``{qualify(a['type'])}``"
                    + (", only for one of the overloads." if a["default"] == "(overload)" else
                       f", default ``{a['default']}``." if a["default"] is not None else ".") for a in b["args"]]
            doc += [f"    {py_ident(p['name'])} ({p['py']}): factory parameter (``{p['type']}``)." for p in kw_params]
            if dtypes:
                combos = inst[f"Factory::{name}"]["builders"][b["name"]]["combos"]
                doc += [f"    {d} (streampu.dtype): template parameter ``{d}``." for d in dtypes]
                doc += ["", "Compiled dtype combinations (" + ", ".join(dtypes) + "): "
                        + "; ".join("(" + ", ".join(c) + ")" for c in combos) + "."]
            doc += ["", "Returns:", f"    {ret_doc}: the built object (owned by Python)."]
            pmap = ", ".join(f'"{p["name"]}": {py_ident(p["name"])}' for p in all_params
                             if p["name"] in sizes or p in kw_params)
            amap = ", ".join(f'"{a["name"]}": {py_ident(a["name"])}' for a in b["args"])
            dmap = ", ".join(f'"{d}": {d}' for d in dtypes)
            body = (f'    return _make("{name}", "{b["name"]}", {{{pmap}}}, {{{amap}}}, {{{dmap}}})')
            doc_txt = "\n".join(("    " + l) if l else "" for l in doc)
            assert not set(dtypes) & {p["name"] for p in kw_params}, (name, dtypes)
            internal = f"_{module.replace('.', '_')}__{fname}"  # unique in this file; renamed at export
            ann = return_annotation(api, status, python_paths, qualify(b["ret"]),
                                    inst.get(f"Factory::{name}", {}).get("builders", {}).get(b["name"], {}).get("combos"))
            code.append(f"\n\ndef {internal}({signature}) -> {ann}:\n    \"\"\"{doc_txt.lstrip()}\n    \"\"\"\n{body}\n")
            funcs.setdefault(module, [])
            assert fname not in [f for f, _ in funcs[module]], (module, fname)
            funcs[module].append((fname, internal))
    code.append("\n\n# functions exported by each sub-module of aff3ct: {sub-module: {public name: function}}\nFUNCTIONS = {\n"
                + "".join(f'    "{m}": {{' + ", ".join(f'"{f}": {i}' for f, i in fs) + "},\n"
                          for m, fs in sorted(funcs.items())) + "}\n")
    code.append("\n# codec factories: {factory: {function: public name, args: builder arguments}} (functions: aff3ct/codec.py)\n"
                f"CODECS = {pprint.pformat(codecs, width=116, sort_dicts=True)}\n")
    code.append("\n# builders without function (the class they return is not wrapped yet)\nSKIPPED = [\n"
                + "".join(f'    "{s}",\n' for s in skipped) + "]\n")
    write(PY_GEN / "functions.py", "\n".join(code))
    n_fun = sum(len(v) for v in funcs.values())
    n_build = sum(len(v) for v in builders_of.values())
    print(f"{len(order)} factories, {n_build} builders -> internal/src/Generated; "
          f"{n_fun} functions ({len(skipped)} skipped: class or argument not wrapped) -> aff3ct/_generated/functions.py")


if __name__ == "__main__":
    main()
